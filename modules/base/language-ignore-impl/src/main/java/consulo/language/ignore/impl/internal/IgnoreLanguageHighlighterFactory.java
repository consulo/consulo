package consulo.language.ignore.impl.internal;

import consulo.annotation.component.ExtensionImpl;
import consulo.language.Language;
import consulo.language.editor.highlight.SyntaxHighlighter;
import consulo.language.editor.highlight.SyntaxHighlighterFactory;
import consulo.language.ignore.IgnoreLanguage;
import consulo.project.Project;
import consulo.virtualFileSystem.VirtualFile;
import org.jspecify.annotations.Nullable;

@ExtensionImpl
public final class IgnoreLanguageHighlighterFactory extends SyntaxHighlighterFactory {
    @Override
    public Language getLanguage() {
        return IgnoreLanguage.INSTANCE;
    }

    @Override
    public SyntaxHighlighter getSyntaxHighlighter(@Nullable Project project, @Nullable VirtualFile virtualFile) {
        return new IgnoreLanguageHighlighter(virtualFile);
    }
}
