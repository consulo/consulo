package consulo.language.editor.impl.internal.highlight;

import consulo.codeEditor.markup.RangeHighlighterEx;
import consulo.document.util.TextRangeScalarUtil;
import consulo.language.editor.impl.highlight.HighlightingSession;
import consulo.language.editor.impl.internal.rawHighlight.HighlightInfoImpl;
import consulo.localize.LocalizeValue;
import org.jspecify.annotations.Nullable;

import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Consumer;

/**
 * Cache for highlighters scheduled for removal.
 * You call {@link #recycleHighlighter} to put unused highlighter into the cache
 * and then call {@link #pickupHighlighterFromGarbageBin} (if there is a sudden need for fresh highlighter with specified offsets) to remove it from the cache to re-initialize and re-use.
 * In the end, remaining highlighters left in the cache that nobody picked up and reused are disposed.
 */
final class HighlighterRecycler {
    // range -> list of highlighters in this range; these are loose highlighters (ones which are generated by some non-managed pass, meaning other than GHP/LIP)
    private final Map<Long, List<HighlightInfoImpl>> incinerator = new HashMap<>();

    /**
     * do not instantiate, use {@link #runWithRecycler} instead
     */
    private HighlighterRecycler() {
    }

    // return true if RH is successfully recycled, false if race condition intervened
    synchronized void recycleHighlighter(HighlightInfoImpl info) {
        RangeHighlighterEx highlighter = info.getHighlighter();
        assert highlighter != null;
        if (UpdateHighlightersUtilImpl.LOG.isDebugEnabled()) {
            UpdateHighlightersUtilImpl.LOG.debug("recycleHighlighter " + info);
        }
        long range = TextRangeScalarUtil.toScalarRange(highlighter);
        incinerator.computeIfAbsent(range, __ -> new ArrayList<>()).add(info);
    }

    // null means no highlighter found in the cache
    synchronized @Nullable RangeHighlighterEx pickupHighlighterFromGarbageBin(
        int startOffset,
        int endOffset,
        int layer,
        @Nullable LocalizeValue preferredDescription
    ) {
        long range = TextRangeScalarUtil.toScalarRange(startOffset, endOffset);
        List<HighlightInfoImpl> list = incinerator.get(range);
        if (list == null) {
            return null;
        }
        int i;
        int previousFound = -1;
        for (i = list.size() - 1; i >= 0; i--) {
            HighlightInfoImpl info = list.get(i);
            RangeHighlighterEx highlighter = info.getHighlighter();
            if (highlighter.isValid() && highlighter.getLayer() == layer) {
                if (Objects.equals(info.getDescription(), preferredDescription)) {
                    break;
                }
                else {
                    previousFound = i;
                }
            }
        }
        if (i == -1) {
            i = previousFound;
            if (i == -1) {
                return null;
            }
        }
        HighlightInfoImpl info = list.remove(i);
        if (list.isEmpty()) {
            incinerator.remove(range);
        }
        if (UpdateHighlightersUtilImpl.LOG.isDebugEnabled()) {
            UpdateHighlightersUtilImpl.LOG.debug("pickupHighlighterFromGarbageBin pickedup:" + info);
        }
        return info.getHighlighter();
    }

    private synchronized Collection<? extends HighlightInfoImpl> forAllInGarbageBin() {
        List<HighlightInfoImpl> result = new ArrayList<>();
        for (List<HighlightInfoImpl> infos : incinerator.values()) {
            result.addAll(infos);
        }
        return result;
    }

    /**
     * - create {@link HighlighterRecycler},
     * - run {@code consumer} which usually calls {@link HighlighterRecycler#recycleHighlighter} and {@link HighlighterRecycler#pickupHighlighterFromGarbageBin}
     * - and then incinerate all remaining highlighters, or in the case of PCE, release them back to recyclable state
     */
    static void runWithRecycler(HighlightingSession session, Consumer<? super HighlighterRecycler> consumer) {
        HighlighterRecycler recycler = new HighlighterRecycler();
        consumer.accept(recycler);
        for (HighlightInfoImpl info : recycler.forAllInGarbageBin()) {
            UpdateHighlightersUtilImpl.disposeWithFileLevelIgnoreErrors(info, session);
        }
    }

    synchronized boolean isEmpty() {
        return incinerator.isEmpty();
    }
}
